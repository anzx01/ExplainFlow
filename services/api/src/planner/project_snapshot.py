"""Stable project snapshots and stage fingerprints for incremental rendering."""

from __future__ import annotations

import hashlib
import json
from typing import Any


SNAPSHOT_VERSION = 2


def canonical_json(value: Any) -> str:
    return json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":"), default=str)


def fingerprint(value: Any, *, namespace: str = "explainflow") -> str:
    payload = f"{namespace}:v{SNAPSHOT_VERSION}:{canonical_json(value)}".encode("utf-8")
    return hashlib.sha256(payload).hexdigest()


def build_project_snapshot(
    storyboard: dict[str, Any],
    *,
    model: str | None = None,
    style_snapshot: dict[str, Any] | None = None,
    render_config: dict[str, Any] | None = None,
) -> dict[str, Any]:
    """Build a portable manifest; paths and generated bytes stay outside the snapshot."""
    scenes = storyboard.get("scenes") if isinstance(storyboard.get("scenes"), list) else []
    normalized = {
        "topic": storyboard.get("topic"),
        "video_style": storyboard.get("video_style", storyboard.get("videoStyle")),
        "pen_style": storyboard.get("pen_style", storyboard.get("penStyle")),
        "style_lock": storyboard.get("style_lock", storyboard.get("styleLock")),
        "character_lock": storyboard.get("character_lock", storyboard.get("characterLock")),
        "palette_id": storyboard.get("palette_id", storyboard.get("paletteId")),
        "style_fingerprint": storyboard.get("style_fingerprint", storyboard.get("styleFingerprint")),
        "character_fingerprint": storyboard.get("character_fingerprint", storyboard.get("characterFingerprint")),
        "scenes": scenes,
    }
    storyboard_fp = fingerprint(normalized, namespace="storyboard")
    style_fp = fingerprint(style_snapshot or {}, namespace="style")
    render_fp = fingerprint(render_config or {}, namespace="render")
    return {
        "snapshotVersion": SNAPSHOT_VERSION,
        "storyboardFingerprint": storyboard_fp,
        "styleFingerprint": style_fp,
        "renderFingerprint": render_fp,
        "model": model,
        "sceneFingerprints": {
            str(scene.get("id") or index): fingerprint(scene, namespace="scene")
            for index, scene in enumerate(scenes)
        },
        "stages": {
            "storyboard": storyboard_fp,
            "images": fingerprint({"storyboard": storyboard_fp, "style": style_fp}, namespace="images"),
            "audio": fingerprint({"storyboard": storyboard_fp}, namespace="audio"),
            "render": fingerprint(
                {"storyboard": storyboard_fp, "style": style_fp, "render": render_fp},
                namespace="render-stage",
            ),
        },
    }
